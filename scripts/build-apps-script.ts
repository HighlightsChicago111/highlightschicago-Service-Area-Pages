/**
 * Builds apps-script/ServiceAreaPages.gs, the file pasted into the Google Sheet's Apps Script project.
 *
 *   pnpm apps-script:build
 *
 * The column list is generated from the areaPage Sanity schema, and the row checks are the same modules
 * `pnpm sheet:import` uses, so the sheet and Sanity can't drift. Rebuild (and re-paste) after a schema change;
 * `pnpm test:content` fails while the committed file is out of date.
 */
import fs from 'node:fs'
import path from 'node:path'
import {build} from 'esbuild'
import {areaPage} from '../src/sanity/schemaTypes/areaPage'
import {sheetColumns, type SchemaField} from './lib/sheet'

export const OUT_FILE = path.resolve('apps-script/ServiceAreaPages.gs')

export async function buildAppsScript(): Promise<string> {
  const columns = sheetColumns((areaPage as unknown as {fields: SchemaField[]}).fields)
  const config = JSON.parse(fs.readFileSync(path.resolve('apps-script/config.json'), 'utf8'))
  const result = await build({
    entryPoints: [path.resolve('apps-script/src/service-area-pages.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'ServiceAreaPagesLib',
    target: 'es2020',
    platform: 'neutral',
    charset: 'utf8',
    legalComments: 'none',
    define: {__COLUMNS__: JSON.stringify(columns), __CONFIG__: JSON.stringify(config)},
  })
  const header = [
    '// Service area pages -> Sanity (tab "Service area pages" only).',
    '// GENERATED by `pnpm apps-script:build` in HighlightsChicago111/highlightschicago-Service-Area-Pages.',
    '// Do not edit here: change apps-script/src/service-area-pages.ts or the Sanity schema, rebuild, re-paste.',
    `// ${columns.length} field columns from the areaPage schema; Sanity project ${config.projectId}, dataset ${config.dataset}.`,
    '',
  ].join('\n')
  const entryPoints = [
    '',
    '// Menu actions (global names, so they never clash with other tabs\' scripts in this spreadsheet).',
    'function serviceAreaPagesMenu() { ServiceAreaPagesLib.menu() }',
    'function serviceAreaPagesCheck() { ServiceAreaPagesLib.check() }',
    'function serviceAreaPagesPush() { ServiceAreaPagesLib.push() }',
    'function serviceAreaPagesSetToken() { ServiceAreaPagesLib.setToken() }',
    'function serviceAreaPagesLoad() { ServiceAreaPagesLib.load() }',
    '',
  ].join('\n')
  return header + result.outputFiles[0].text + entryPoints
}

if (process.argv[1] && path.resolve(process.argv[1]).replace(/\.ts$/, '') === path.resolve('scripts/build-apps-script').replace(/\.ts$/, '')) {
  buildAppsScript().then((code) => {
    fs.writeFileSync(OUT_FILE, code)
    console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)} (${Math.round(code.length / 1024)} KB). Paste it into the sheet's Apps Script project as ServiceAreaPages.gs.`)
  }).catch((error: unknown) => { console.error(error); process.exit(1) })
}
